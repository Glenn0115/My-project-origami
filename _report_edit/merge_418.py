def para_text(p):
    return "".join(n.text or "" for n in p.iter(qn("w:t")))

def find_para(anchor, startswith=True):
    for p in body.findall(qn("w:p")):
        t = para_text(p)
        if (t.startswith(anchor) if startswith else t == anchor):
            return p
    raise SystemExit("NOT FOUND: " + anchor)

def para_with_image(fname):
    for p in body.findall(qn("w:p")):
        for blip in p.iter(qn("a:blip")):
            if media.get(blip.get(qn("r:embed"))) == fname:
                return p
    raise SystemExit("IMG NOT FOUND: " + fname)

def set_text(p, text):
    rpr = None
    for r in p.findall(qn("w:r")):
        if r.find(qn("w:t")) is not None and r.find(qn("w:drawing")) is None:
            if r.find(qn("w:rPr")) is not None:
                rpr = deepcopy(r.find(qn("w:rPr")))
            break
    for child in list(p):
        if child.tag.split("}")[-1] in ("r", "hyperlink"):
            if child.find(qn("w:drawing")) is None and child.find(qn("w:pict")) is None:
                p.remove(child)
    run = OxmlElement("w:r")
    if rpr is not None:
        run.append(rpr)
    t = OxmlElement("w:t")
    t.set(qn("xml:space"), "preserve")
    t.text = text
    run.append(t)
    ppr = p.find(qn("w:pPr"))
    p.insert(1 if ppr is not None else 0, run)

def clone_para(p):
    c = deepcopy(p)
    for r in list(c.findall(qn("w:r"))):
        c.remove(r)
    return c

def is_empty_para(p):
    if p.find(qn("w:drawing")) is not None or p.find(qn("w:pict")) is not None:
        return False
    return para_text(p).strip() == ""


# ---------- helpers ----------
def para_text(p):
    return "".join(n.text or "" for n in p.iter(qn("w:t")))

def get_paras():
    return body.findall(qn("w:p"))

def find_para(pred):
    for p in get_paras():
        if pred(para_text(p)):
            return p
    raise RuntimeError("para not found")

def set_text(p, text):
    """Replace text of paragraph p, preserving pPr and drawing runs; copy rPr from first text run."""
    # find rPr of first text run
    rpr = None
    for r in p.findall(qn("w:r")):
        if r.find(qn("w:t")) is not None and r.find(qn("w:drawing")) is None:
            rpr = r.find(qn("w:rPr"))
            if rpr is not None:
                rpr = deepcopy(rpr)
            break
    # remove text runs and hyperlinks (keep drawings)
    for child in list(p):
        tag = child.tag.split("}")[-1]
        if tag in ("r", "hyperlink"):
            if child.find(qn("w:drawing")) is None and child.find(qn("w:pict")) is None:
                p.remove(child)
    # build new run
    run = OxmlElement("w:r")
    if rpr is not None:
        run.append(rpr)
    t = OxmlElement("w:t")
    t.set(qn("xml:space"), "preserve")
    t.text = text
    run.append(t)
    ppr = p.find(qn("w:pPr"))
    p.insert(1 if ppr is not None else 0, run)

def delete_para(p):
    p.getparent().remove(p)

def insert_after(anchor, new_el):
    anchor.addnext(new_el)

def clone_para(template_el, text):
    el = deepcopy(template_el)
    set_text(el, text)
    return el

